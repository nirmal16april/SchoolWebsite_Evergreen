function toHighlightTopper(student, index, classLevel, academicYear) {
  return {
    id: `${classLevel}-${academicYear}-${index + 1}`,
    name: student.name,
    score: student.score,
    rank: index + 1,
    photo: student.photo,
    classLevel,
    academicYear,
  };
}

